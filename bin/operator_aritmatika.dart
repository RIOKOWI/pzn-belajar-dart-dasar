void main(){
  // + = pertambahan
  // - = perkurangan
  // * = perkalian
  // / = pembagian hasil double
  // ~/ = pembagian hasil int
  // % = sisa pembagian / modulus

  var tambah = 10 + 1;
  var kurang = 10 - 5;
  var kali = 5 * 5;
  var minus = -5;
  var bagiDoub = 10 / 3;
  var bagiInt = 10 ~/ 3;
  var modulus = 10 % 3;

  print(tambah);
  print(kurang);
  print(kali);
  print(minus);
  print(bagiDoub);
  print(bagiInt);
  print(modulus);
}